// Kept as a standalone CommonJS file in the customer's project: a client can
// start it from any directory, without putting a credential in its MCP config.
export const MCP_VERSION = "0.2.2";
export const AGENT_LAUNCHER = `// Generated by affitor agent setup. Contains no credentials.
const { readFileSync, lstatSync } = require('node:fs');
const { join, resolve } = require('node:path');
const { spawn } = require('node:child_process');
const project = resolve(__dirname, '..');
let key = process.env.AFFITOR_API_KEY;
if (!key) {
  try {
    const path = join(__dirname, '.env');
    if (!lstatSync(path).isFile() || lstatSync(path).isSymbolicLink()) throw new Error();
    const lines = readFileSync(path, 'utf8').split(/\\r?\\n/);
    const values = lines.filter(line => /^\\s*(?:export\\s+)?AFFITOR_API_KEY\\s*=/.test(line));
    if (values.length !== 1) throw new Error();
    key = values[0].replace(/^\\s*(?:export\\s+)?AFFITOR_API_KEY\\s*=\\s*/, '').trim();
    if ((key.startsWith('"') && key.endsWith('"')) || (key.startsWith("'") && key.endsWith("'"))) key = key.slice(1, -1);
    if (!/^[A-Za-z0-9_-]+$/.test(key)) throw new Error();
  } catch {
    process.stderr.write('Affitor: set AFFITOR_API_KEY or configure this project with affitor init. No agent call was made.\\n');
    process.exit(1);
  }
}
// Setup never opts into the sale/refund tools, including through inherited env.
const env = { ...process.env, AFFITOR_API_KEY: key, AFFITOR_MCP_WRITE: '0' };
delete env.AFFITOR_API_URL;
const child = spawn(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['-y', '@affitor/mcp@${MCP_VERSION}'], { cwd: project, env, stdio: 'inherit', shell: false });
child.on('error', () => { process.stderr.write('Affitor: could not start the pinned MCP. Check Node.js, npm and network access.\\n'); process.exitCode = 1; });
child.on('exit', (code, signal) => { process.exitCode = signal ? 1 : (code ?? 1); });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
`;

