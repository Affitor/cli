// Kept as a standalone CommonJS file in the customer's project: a client can
// start it from any directory, without putting a credential in its MCP config.
export const MCP_VERSION = "0.2.2";

/** Shared by doctor and the generated launcher; never evaluates an env file. */
export function parseProgramCredential(envKey: unknown, readText: () => string | null): string | null {
  const valid = (value: string) => /^[A-Za-z0-9_-]+$/.test(value);
  if (typeof envKey === "string" && envKey !== "") return valid(envKey) ? envKey : null;
  try {
    const text = readText();
    if (text === null) return null;
    const assignments = text.split(/\r?\n/).filter(line => /^\s*(?:export\s+)?AFFITOR_API_KEY\s*=/.test(line));
    if (assignments.length !== 1) return null;
    let value = assignments[0].replace(/^\s*(?:export\s+)?AFFITOR_API_KEY\s*=\s*/, "").trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    return valid(value) ? value : null;
  } catch { return null; }
}

/** Minimal runtime environment; never forward parent networking, Node or npm overrides. */
export function agentChildEnvironment(source: NodeJS.ProcessEnv, key: string): NodeJS.ProcessEnv {
  const allowed = ["PATH", "HOME", "USERPROFILE", "APPDATA", "LOCALAPPDATA", "SYSTEMROOT", "WINDIR", "COMSPEC", "PATHEXT", "TMP", "TEMP", "TMPDIR", "LANG", "TERM", "COLORTERM", "NO_COLOR", "FORCE_COLOR"];
  const env: NodeJS.ProcessEnv = {};
  for (const [name, value] of Object.entries(source)) {
    const canonical = name.toUpperCase();
    if (allowed.includes(canonical) || /^LC_[A-Z_]+$/.test(canonical)) env[canonical] = value;
  }
  env.NoDefaultCurrentDirectoryInExePath = "1";
  env.AFFITOR_API_KEY = key;
  env.AFFITOR_MCP_WRITE = "0";
  return env;
}

export const AGENT_LAUNCHER = `// Generated by affitor agent setup. Contains no credentials.
const { readFileSync, lstatSync } = require('node:fs');
const { join, resolve } = require('node:path');
const { spawn } = require('node:child_process');
const project = resolve(__dirname, '..');
const parseProgramCredential = ${parseProgramCredential.toString()};
const key = parseProgramCredential(process.env.AFFITOR_API_KEY, () => {
  const path = join(__dirname, '.env');
  const stat = lstatSync(path);
  if (!stat.isFile() || stat.isSymbolicLink()) return null;
  return readFileSync(path, 'utf8');
});
if (!key) {
  process.stderr.write('Affitor: set AFFITOR_API_KEY or configure this project with affitor init. No agent call was made.\\n');
  process.exit(1);
}
// Setup never opts into the sale/refund tools, including through inherited env.
const agentChildEnvironment = ${agentChildEnvironment.toString()};
const env = agentChildEnvironment(process.env, key);
// Windows batch files require cmd.exe. The command contains constants only:
// project paths and credentials travel through cwd/env, never shell text.
const windows = process.platform === 'win32';
const command = windows ? (process.env.ComSpec || 'cmd.exe') : 'npx';
const args = windows ? ['/d', '/s', '/c', 'npx.cmd --registry=https://registry.npmjs.org -y @affitor/mcp@${MCP_VERSION}'] : ['--registry=https://registry.npmjs.org', '-y', '@affitor/mcp@${MCP_VERSION}'];
const child = spawn(command, args, { cwd: project, env, stdio: 'inherit', shell: false, windowsHide: true });
child.on('error', () => { process.stderr.write('Affitor: could not start the pinned MCP. Check Node.js, npm and network access.\\n'); process.exitCode = 1; });
child.on('exit', (code, signal) => { process.exitCode = signal ? 1 : (code ?? 1); });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
`;

